export const getInitialLang = () => {
    if (typeof window !== 'undefined') {
        const stored = localStorage.getItem('ekrishi_lang');
        if (stored === 'bn' || stored === 'en') {
            return stored;
        }
    }
    // Default is strictly English as requested: "বাই ডিফল্ট সবকিছু ইংলিশ থাকবে কোন কিছু বাংলা থাকবে না"
    return 'en';
};

export const saveLang = (lang) => {
    if (typeof window !== 'undefined') {
        localStorage.setItem('ekrishi_lang', lang);
        document.cookie = `ekrishi_lang=${lang};path=/;max-age=31536000`;
    }
};

